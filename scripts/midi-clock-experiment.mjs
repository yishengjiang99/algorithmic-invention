#!/usr/bin/env node
/**
 * Experiment: raw last-interval vs rolling-median + phase-correction MIDI clock
 * estimation. Re-runnable and deterministic (seeded PRNG, no wall clock).
 *
 *   node scripts/midi-clock-experiment.mjs            # rewrite docs/midi-clock-experiment.md
 *   node scripts/midi-clock-experiment.mjs --check    # exit 1 if the committed doc is stale
 *   node scripts/midi-clock-experiment.mjs --stdout   # print instead of writing
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createEstimator, DEFAULTS } from "../public/midi-clock/estimator.js";
import { generateTrace } from "../public/midi-clock/synthetic.js";
import { replay, judge, THRESHOLDS } from "../public/midi-clock/replay.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "docs", "midi-clock-experiment.md");

export const HEADLINE_SEED = 20261018;
export const SWEEP_SEEDS = Array.from({ length: 20 }, (_, i) => i + 1);
export const TRACE = {
  bpm: 120,
  durationMs: 120000,
  jitterMs: 3,
  dropRate: 0.01,
  delayEvery: 64,
  delayMs: 20,
};
const KINDS = ["last-interval", "filtered"];

const f = (x, d = 3) =>
  x === null || x === undefined
    ? "never"
    : !Number.isFinite(x)
      ? String(x)
      : x >= 1e5
        ? x.toExponential(2)
        : x.toFixed(d);

function run(seed, kind) {
  const trace = generateTrace({ seed, ...TRACE });
  const r = replay(createEstimator(kind), trace);
  return { r, verdict: judge(r), trace };
}

function median(a) {
  const s = [...a].sort((x, y) => x - y);
  const n = s.length;
  return n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2;
}

export function buildReport() {
  const head = {};
  for (const k of KINDS) head[k] = run(HEADLINE_SEED, k);
  const sweep = {};
  for (const k of KINDS) sweep[k] = SWEEP_SEEDS.map((s) => run(s, k));

  const L = [];
  const row = (label, get) =>
    L.push(`| ${label} | ${KINDS.map((k) => get(head[k].r, head[k].verdict)).join(" | ")} |`);
  const tr = head["filtered"].trace;

  L.push("# MIDI clock: raw timing vs jitter-resistant estimation", "");
  L.push(
    "Generated by `node scripts/midi-clock-experiment.mjs` (do not edit by hand; `npm test` fails if this file is stale).",
    "Every number below is measured by that script from seeded synthetic traces; nothing is hand-entered.",
    "",
  );
  L.push("## Question", "");
  L.push(
    "Can a Web MIDI clock follower get a usable tempo and beat phase from the timestamps of F8 messages when those timestamps are noisy, or is the last interval enough?",
    "",
  );
  L.push("## Hypothesis (fixed before measuring)", "");
  L.push(
    `The rolling-median + phase-correction estimator ("filtered") settles within ${THRESHOLDS.settleMs / 1000} s, with BPM error below ${THRESHOLDS.bpmError} and p95 beat-phase error below ${THRESHOLDS.phaseP95Ms} ms. The last-interval estimate is the baseline.`,
    "",
  );
  L.push("## Method", "");
  L.push(
    `- Trace: ${TRACE.bpm} BPM, 24 clocks per beat (ideal period ${(60000 / (TRACE.bpm * 24)).toFixed(4)} ms), ${TRACE.durationMs / 1000} s, ${tr.trueTimes.length} ideal clocks.`,
    `- Timestamp jitter: uniform ±${TRACE.jitterMs} ms on every message.`,
    `- Missing clocks: each message is dropped with probability ${TRACE.dropRate * 100}% (independent).`,
    `- Delivery delay: every ${TRACE.delayEvery}th clock is stamped ${TRACE.delayMs} ms late. At 120 BPM a tick is 20.83 ms, so a delayed clock is often reordered behind its successor; observed timestamps are sorted, as a receiver would see them.`,
    `- PRNG: mulberry32. Headline seed ${HEADLINE_SEED} (${head["filtered"].r.messagesDelivered} messages delivered). A 20-seed sweep (seeds 1 to 20) checks the headline is not a lucky draw.`,
    "- Causal replay: at every 1 ms instant the estimator has only seen messages stamped at or before that instant. Phase error is the distance (wrapped to one beat, in ms) between the estimator's tick position and the true tick position at that instant; BPM error is |estimate − 120|.",
    `- Steady-state statistics use t ≥ 2 s. **Settling time** is one millisecond after the last instant at which phase error ≥ ${THRESHOLDS.phaseP95Ms} ms or BPM error ≥ ${THRESHOLDS.bpmError} (or no estimate exists); "never" means it was still violating at the end of the trace. The BPM gate is the stricter **maximum** over steady state, not p95.`,
    "- Resynchronizations: *internal* = hard re-anchors the estimator reports (gap too long, tempo step, phase target off by more than 15 ms). *Visible phase jumps* = clock arrivals where the predicted tick position moved by more than 5 ms, measured from outside, which is meaningful for the baseline because it re-anchors on every message.",
    "- Filtered estimator parameters (defaults, untuned): " +
      Object.entries(DEFAULTS)
        .map(([k, v]) => `${k}=${v}`)
        .join(", ") +
      ".",
    "",
  );

  L.push(`## Results: headline seed ${HEADLINE_SEED}`, "");
  L.push(`| Metric | ${KINDS.join(" | ")} |`, `| --- | ${KINDS.map(() => "---").join(" | ")} |`);
  row("Settling time (ms)", (r) => f(r.settleMs, 0));
  row("First instant inside band (ms)", (r) => f(r.firstInBandMs, 0));
  row("Phase error median (ms)", (r) => f(r.phaseMedianMs));
  row("Phase error p95 (ms)", (r) => f(r.phaseP95Ms));
  row("Phase error max (ms)", (r) => f(r.phaseMaxMs));
  row("BPM error median", (r) => f(r.bpmMedianErr));
  row("BPM error p95", (r) => f(r.bpmP95Err));
  row("BPM error max", (r) => f(r.bpmMaxErr));
  row("Resynchronizations (internal)", (r) => String(r.resyncs));
  row("Visible phase jumps > 5 ms", (r) => String(r.phaseJumps));
  row("Duplicate/reordered stamps dropped", (r) => String(r.duplicatesDropped));
  row("Missing clocks inferred", (r) => String(r.gapsFilled));
  row("Settles within 2 s", (_r, v) => (v.settle ? "PASS" : "FAIL"));
  row(`BPM error max < ${THRESHOLDS.bpmError}`, (_r, v) => (v.bpm ? "PASS" : "FAIL"));
  row(`Phase p95 < ${THRESHOLDS.phaseP95Ms} ms`, (_r, v) => (v.phase ? "PASS" : "FAIL"));
  row("**Meets all three**", (_r, v) => (v.all ? "**YES**" : "**NO**"));
  L.push("");

  L.push("## Seed sweep (seeds 1 to 20)", "");
  L.push(`| Metric | ${KINDS.join(" | ")} |`, `| --- | ${KINDS.map(() => "---").join(" | ")} |`);
  const sw = (label, get, fmt) =>
    L.push(`| ${label} | ${KINDS.map((k) => fmt(sweep[k].map(get))).join(" | ")} |`);
  const g = (x, d) => (x === Infinity ? "never" : f(x, d));
  const mm = (d) => (a) => `${g(Math.min(...a), d)} / ${g(median(a), d)} / ${g(Math.max(...a), d)}`;
  sw(
    "Seeds meeting all three",
    (x) => (x.verdict.all ? 1 : 0),
    (a) => `${a.reduce((s, v) => s + v, 0)} / ${a.length}`,
  );
  sw(
    "Settling time ms (min / median / max)",
    (x) => (x.r.settleMs === null ? Infinity : x.r.settleMs),
    mm(0),
  );
  sw("Phase p95 ms (min / median / max)", (x) => x.r.phaseP95Ms, mm(3));
  sw("BPM error max (min / median / max)", (x) => x.r.bpmMaxErr, mm(3));
  sw("Resyncs internal (min / median / max)", (x) => x.r.resyncs, mm(0));
  L.push("");

  const winner = KINDS.filter((k) => head[k].verdict.all);
  const sweepWinner = KINDS.filter((k) => sweep[k].every((x) => x.verdict.all));
  const chosen = KINDS.filter((k) => winner.includes(k) && sweepWinner.includes(k));
  L.push("## Selection", "");
  L.push(
    chosen.length
      ? `Selected estimator: **${chosen[0]}**. It meets all three thresholds on the headline seed and on all ${SWEEP_SEEDS.length} sweep seeds.`
      : `No estimator met all three thresholds on the headline seed and every sweep seed. Headline pass: ${winner.join(", ") || "none"}.`,
    "",
  );
  const base = head["last-interval"].r;
  L.push(
    `Why the baseline fails (measured above): one ±${TRACE.jitterMs} ms timestamp error moves a single interval by up to ±${2 * TRACE.jitterMs} ms, which is up to ±29% of a 20.83 ms tick, so its median BPM error is ${f(base.bpmMedianErr, 1)} and its p95 is ${f(base.bpmP95Err, 1)}. When a delayed clock is reordered behind its successor the two stamps are almost equal and the "last interval" is close to zero, which explains why the maximum BPM error is astronomically large (${f(base.bpmMaxErr, 0)}); a dropped clock makes the interval double and halves the reading. It also re-anchors its phase on every message (${base.phaseJumps} visible jumps above ${5} ms) and its tick counter counts messages rather than ticks, so every missing clock shifts phase by one tick (20.8 ms) permanently. Its phase error wraps at half a beat (250 ms), and a median of ${f(base.phaseMedianMs, 0)} ms means it is effectively unsynchronised.`,
    "",
  );
  L.push("## Limits (what this does not show)", "");
  L.push(
    "- Synthetic traces only. Real devices and OS MIDI stacks have non-uniform jitter (bursts, quantised stamps), which this does not model.",
    "- Constant tempo. Tempo changes (the 120 → 90 BPM step) are covered by the unit tests in `src/lib/midi-clock/` (see `docs/midi-clock-follower.md`), not by this experiment.",
    "- The estimator parameters were not tuned against these seeds; they are the module defaults.",
    "- Phase error is measured against the generator's ideal tick grid, so it excludes audio output latency and the performance.now to AudioContext conversion error (see `docs/midi-clock-follower.md`).",
    "",
  );
  L.push("## Re-run", "", "```bash", "node scripts/midi-clock-experiment.mjs", "```", "");
  return L.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const report = buildReport();
  if (process.argv.includes("--stdout")) process.stdout.write(report);
  else if (process.argv.includes("--check")) {
    let cur = "";
    try {
      cur = readFileSync(OUT, "utf8");
    } catch {
      /* missing */
    }
    if (cur !== report) {
      console.error(
        "docs/midi-clock-experiment.md is stale; run: node scripts/midi-clock-experiment.mjs",
      );
      process.exit(1);
    }
    console.log("docs/midi-clock-experiment.md is up to date");
  } else {
    writeFileSync(OUT, report);
    console.log(`wrote ${OUT}`);
  }
}
